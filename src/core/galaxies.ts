/** A galaxy's name, by index (0 is Euclid). */
export function galaxyName(index: number): string {
  const name = GALAXY_NAMES[index];
  if (name === undefined) throw new RangeError(`There is no galaxy with index ${index}.`);
  return name;
}

/** How the site names a galaxy, by index: as players number it, then its name ("Galaxy 2: Hilbert Dimension"). */
export function galaxyLabel(index: number): string {
  return `Galaxy ${index + 1}: ${galaxyName(index)}`;
}
